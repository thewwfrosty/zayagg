function saveEditedProfile(e) {

  e.preventDefault();

  const name =
    $("editName")
      .value
      .trim();

  const username =
    $("editUsername")
      .value
      .trim();

  const bio =
    $("editBio")
      .value
      .trim();

  if (!name || !username) {
    return;
  }

  profileData.name =
    name;

  profileData.username =
    username.startsWith("@")
      ? username
      : "@" + username;

  profileData.bio =
    bio ||
    DEFAULT_PROFILE.bio;

  saveProfile();

  renderProfile();

  closeEditProfile();
}


/* RECORD TRADE */

function recordTradeResult(status) {

  if (
    !youTrade.length ||
    !themTrade.length
  ) {
    return;
  }

  const key =
    youTrade
      .map(p => p.uniqueId)
      .join(",") +
    "|" +
    themTrade
      .map(p => p.uniqueId)
      .join(",") +
    "|" +
    status;

  if (
    key === recordedTradeKey
  ) {
    return;
  }

  recordedTradeKey = key;

  profileData.stats.trades++;

  if (status === "win") {
    profileData.stats.wins++;
  }

  if (status === "fair") {
    profileData.stats.fairs++;
  }

  if (status === "lose") {
    profileData.stats.loses++;
  }

  saveProfile();
}


