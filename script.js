function updateResult(y, t) {

  const card = $("resultCard");
  const status = $("resultStatusText");
  const diff = $("resultDiffNumber");

  card?.classList.remove(
    "win",
    "small-win",
    "fair",
    "small-lose",
    "lose"
  );

  if (y === 0 && t === 0) {
    if (status) {
      status.textContent = "Pet ekleyerek başla";
    }

    if (diff) {
      diff.textContent = "—";
    }

    return;
  }

  /*
    KARŞILAŞTIRMA:

    Karşı taraf daha fazla veriyorsa → WIN
    Biraz daha fazla veriyorsa       → SMALL WIN
    Yakınsa                           → FAIR
    Sen biraz daha fazla veriyorsan  → SMALL LOSE
    Sen çok daha fazla veriyorsan    → LOSE
  */

  const difference = t - y;

  const base = Math.max(y, t);

  const percentage =
    base > 0
      ? Math.abs(difference) / base * 100
      : 0;

  let result;

  if (percentage <= 3) {

    result = "fair";

  } else if (difference > 0) {

    result =
      percentage >= 10
        ? "win"
        : "small-win";

  } else {

    result =
      percentage >= 10
        ? "lose"
        : "small-lose";
  }

  card?.classList.add(result);

  const names = {
    win: "WIN",
    "small-win": "SMALL WIN",
    fair: "FAIR",
    "small-lose": "SMALL LOSE",
    lose: "LOSE"
  };

  if (status) {
    status.textContent = names[result];
  }

  if (diff) {
    diff.textContent =
      difference > 0
        ? `+${formatValue(difference)}`
        : formatValue(difference);
  }

  recordTradeResult(result);
}


/*
  W/F/L:

  Karşı taraf daha fazla veriyor = WIN
  Eşit = FAIR
  Sen daha fazla veriyorsun = LOSE
*/

function updateResult(y, t) {

  const card =
    $("resultCard");

  const status =
    $("resultStatusText");

  const diff =
    $("resultDiffNumber");

  card?.classList.remove(
    "win",
    "lose",
    "fair"
  );

  if (
    y === 0 &&
    t === 0
  ) {

    status.textContent =
      "Pet ekleyerek başla";

    diff.textContent = "—";

    return;
  }

  const difference =
    t - y;

  let result;

  if (
    Math.abs(difference) <= 0.05
  ) {

    result = "fair";

  } else if (
    difference > 0
  ) {

    result = "win";

  } else {

    result = "lose";

  }

  card?.classList.add(
    result
  );

  status.textContent =
    result === "win"
      ? "WIN"
      : result === "lose"
      ? "LOSE"
      : "FAIR";

  diff.textContent =
    difference > 0
      ? `+${formatValue(
          difference
        )}`
      : formatValue(
          difference
        );

  recordTradeResult(
    result
  );
}


