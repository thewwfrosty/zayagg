function getModifiedValue(p) {

  let value =
    Number(p?.value || 0);

  if (selectedForm === "neon") {
    value *= 4;
  }

  if (selectedForm === "mega") {
    value *= 16;
  }

  if (selectedPotion.fly) {
    value += 0.25;
  }

  if (selectedPotion.ride) {
    value += 0.25;
  }

  return value;
}

function updatePickerValue() {

  const el =
    $("pickerValue");

  if (!el) return;

  el.textContent =
    selectedPet
      ? formatValue(
          getModifiedValue(
            selectedPet
          )
        )
      : "0";
}


